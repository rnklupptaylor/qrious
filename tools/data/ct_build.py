"""Real particles from the Zenodo CT scans (van der Haven et al., CC BY 4.0).
For each excipient: pick one particle near the target size, make a light mesh, compute its sieve diameter
(smallest square opening it passes over all orientations), principal dimensions, voxel slices; plus a few full
slices for the animation. Writes v2/parts/ctmesh.js."""
import glob, json, base64, io, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.optimize import minimize
from scipy.spatial.transform import Rotation as Rot
from skimage import measure
import trimesh, fast_simplification

VOX = 6.33
TARGET = {'MCC': 190, 'DCPD': 200, 'PGS': 175}
out = {}
rng = np.random.default_rng(1)

def b64img(im, fmt='PNG', q=80):
    b = io.BytesIO(); im.save(b, fmt, quality=q) if fmt == 'JPEG' else im.save(b, fmt, optimize=True)
    return f'data:image/{fmt.lower()};base64,' + base64.b64encode(b.getvalue()).decode()

def sq_width(P, R):
    Q = P @ R.T
    w = Q[:, :2].max(0) - Q[:, :2].min(0)
    return max(w[0], w[1])

for s in sys.argv[1:]:
    fs = sorted(glob.glob(f'ct/{s}_[0-9]*.tif'))
    raw = np.stack([np.array(Image.open(f)).astype(np.float32) for f in fs])
    V = ndi.gaussian_filter(raw, 1.0)
    bg = np.median(V); hi = np.percentile(V, 99.5); thr = bg + 0.45 * (hi - bg)
    B = ndi.binary_fill_holes(ndi.binary_opening(V > thr, iterations=1))
    L, n = ndi.label(B)
    best = None
    for i, sl in enumerate(ndi.find_objects(L)):
        if sl is None: continue
        if any(d.start <= 1 or d.stop >= L.shape[k] - 1 for k, d in enumerate(sl)): continue
        nv = int((L[sl] == i + 1).sum());
        if nv < 3000: continue
        xv = (6 * nv / np.pi) ** (1 / 3) * VOX
        ext = np.array([d.stop - d.start for d in sl]) * VOX
        if ext.max() > 1.9 * xv: continue  # skip clusters
        sc = abs(np.log(xv / TARGET[s]))
        if best is None or sc < best[0]: best = (sc, i + 1, nv, xv, sl)
    _, lab, nv, xv, sl = best
    sl = tuple(slice(max(0, d.start - 2), min(L.shape[k], d.stop + 2)) for k, d in enumerate(sl))
    M = (L[sl] == lab)
    sub = ndi.gaussian_filter(np.pad(M, 2).astype(np.float32), 0.8)
    v, f, _, _ = measure.marching_cubes(sub, 0.5)
    v = v[:, ::-1] * VOX  # (z,y,x) -> (x,y,z)
    f = f[:, ::-1]
    vv, ff = fast_simplification.simplify(v.astype(np.float32), f.astype(np.int32), target_reduction=max(0, 1 - 700 / len(f)))
    m = trimesh.Trimesh(vv, ff, process=True); m.fix_normals()
    P = m.vertices - m.center_mass
    # principal dimensions: minimal box over random orientations (refined)
    def boxdims(R): Q = P @ R.T; return np.sort(Q.max(0) - Q.min(0))[::-1]
    Rs = Rot.random(4000, random_state=2).as_matrix()
    vol = [np.prod(boxdims(R)) for R in Rs]; Rb = Rs[int(np.argmin(vol))]; dims = boxdims(Rb)
    # sieve diameter: min over orientations of max(width_x, width_y)
    w = np.array([sq_width(P, R) for R in Rs]); k0 = np.argsort(w)[:12]
    bestd, bestR = 1e9, None
    for k in k0:
        q0 = Rot.from_matrix(Rs[k]).as_rotvec()
        r = minimize(lambda q: sq_width(P, Rot.from_rotvec(q).as_matrix()), q0, method='Nelder-Mead', options={'xatol': 1e-4, 'fatol': 1e-3, 'maxiter': 600})
        if r.fun < bestd: bestd, bestR = r.fun, Rot.from_rotvec(r.x).as_matrix()
    # voxel slices of the particle (grey crop of the real CT slices, z = scan axis)
    g = raw[sl]; lo, hi2 = np.percentile(raw, [1, 99.9])
    g8 = (255 * np.clip((g - lo) / (hi2 - lo), 0, 1)).astype(np.uint8)
    nz, ny, nx = g8.shape
    sprite = Image.fromarray(np.concatenate(list(g8), axis=1))  # slices side by side
    mask = Image.fromarray((np.concatenate(list(M), axis=1) * 255).astype(np.uint8))
    # full slices for the animation, downsampled
    full = []
    for z in np.linspace(8, raw.shape[0] - 9, 3).astype(int):
        a = (255 * np.clip((raw[z] - lo) / (hi2 - lo), 0, 1)).astype(np.uint8)
        full.append(b64img(Image.fromarray(a).resize((320, 320), Image.LANCZOS), 'JPEG', 60))

    # equivalent diameters of all complete particles in the stack (for the animation counts)
    out[s] = {
        'v': np.round(P, 1).ravel().tolist(), 'f': m.faces.ravel().tolist(),
        'xV': round(float(xv), 1), 'nvox': nv, 'vox': VOX, 'xVmesh': round(float((6 * m.volume / np.pi) ** (1 / 3)), 1),
        'dims': [round(float(d), 1) for d in dims],
        'sieve': {'d': round(float(bestd), 1), 'R': np.round(bestR, 5).ravel().tolist()},
        'slices': {'n': int(nz), 'w': int(nx), 'h': int(ny), 'grey': b64img(sprite), 'mask': b64img(mask.convert('1'))},
        'full': full,
    }
    print(s, 'particle', lab, 'xV', round(xv), 'mesh xV', out[s]['xVmesh'], 'dims', out[s]['dims'], 'sieve d', round(bestd, 1), 'faces', len(m.faces), 'nz', nz)
js = '/* Generated by ct/build.py from the X-ray CT scans in Zenodo 10.5281/zenodo.16732963 (CC BY 4.0). Do not edit. */\nApp.CTMESH = Object.assign(App.CTMESH || {}, ' + json.dumps(out, separators=(',', ':')) + ');\n'
open('v2/parts/ctmesh_' + '_'.join(sys.argv[1:]) + '.js', 'w').write(js)
print(len(js))
