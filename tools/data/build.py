"""Fraunhofer diffraction of real particle silhouettes (from the Zenodo light-microscope images, CC BY 4.0)
and the sphere that diffracts most like each one. Writes v2/parts/ldpat.js.
Angles: theta in degrees on a log grid. Wavelength 633 nm (He-Ne, as in the Mastersizer 3000 red channel)."""
import json, base64, io
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.special import j1
from scipy.optimize import minimize_scalar
from skimage.filters import threshold_otsu

LAM = 0.633
UMPX = {'MCC': 1.1279, 'DCPD': 0.5646, 'PGS': 0.5646}
TARGET = {'MCC': 160, 'DCPD': 170, 'PGS': 140}
TH = np.logspace(np.log10(0.02), np.log10(12), 160)  # degrees

def b64(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()

def airy(x, th):
    z = np.pi * x * np.sin(np.radians(th)) / LAM
    return np.where(z < 1e-9, 1.0, (2 * j1(z) / np.maximum(z, 1e-9)) ** 2)

def pattern(mask, p):
    N = 4096
    while N < 6 * max(mask.shape): N *= 2
    A = np.zeros((N, N), np.float32); A[:mask.shape[0], :mask.shape[1]] = mask
    F = np.fft.fftshift(np.abs(np.fft.fft2(A)) ** 2)
    F /= F.max()
    c = N // 2; yy, xx = np.indices(F.shape); rr = np.hypot(xx - c, yy - c)  # in frequency bins
    sinth = rr * LAM / (N * p)
    th = np.degrees(np.arcsin(np.clip(sinth, 0, 1)))
    # azimuthal average on the log grid
    ib = np.digitize(th.ravel(), np.r_[0, np.sqrt(TH[1:] * TH[:-1]), 90])
    s = np.bincount(ib, F.ravel(), minlength=len(TH) + 2); n = np.bincount(ib, minlength=len(TH) + 2)
    I = (s / np.maximum(n, 1))[1:len(TH) + 1]; nn = n[1:len(TH) + 1]
    good = nn > 0; I = np.interp(np.log(TH), np.log(TH[good]), np.log(np.maximum(I[good], 1e-12))); I = np.exp(I)
    I[TH < TH[good][0]] = 1.0; I /= I[0]
    # 2D picture of the pattern up to 3 degrees
    lim = int(np.sin(np.radians(3)) * N * p / LAM)
    crop = F[c - lim:c + lim, c - lim:c + lim]
    img = np.clip((np.log10(crop + 1e-12) + 6) / 6, 0, 1) ** 1.3
    pic = Image.fromarray((img * 255).astype(np.uint8)).resize((220, 220), Image.LANCZOS)
    return I, pic

def fitx(I, x0):
    ok = (TH < 12) & (I > 1e-7)
    f = lambda x: np.mean((np.log10(airy(x, TH[ok]) + 1e-7) - np.log10(I[ok] + 1e-7)) ** 2)
    xs = np.linspace(0.5 * x0, 2 * x0, 300); k = int(np.argmin([f(x) for x in xs]))
    r = minimize_scalar(f, bounds=(xs[max(0, k - 1)], xs[min(299, k + 1)]), method='bounded')
    return float(r.x)

out = {'th': [round(float(t), 4) for t in TH], 'lam': LAM}
for s in ['MCC', 'DCPD', 'PGS']:
    cands = []
    import glob as _g
    for fi, fn in enumerate([f'img/om_{s}.png'] + sorted(_g.glob(f'img/om_{s}_[0-9].png'))):
     a = np.asarray(Image.open(fn).convert('L')).astype(float)
     p = 0.5646 * 3584 / a.shape[1]
     g = ndi.gaussian_filter(a, 1.2)
     B = ndi.binary_fill_holes(g < threshold_otsu(g))
     L, n = ndi.label(B)
     for i, sl in enumerate(ndi.find_objects(L)):
         if any(d.start == 0 or d.stop >= B.shape[k] for k, d in enumerate(sl)): continue
         m = L[sl] == i + 1; A = m.sum() * p * p; xa = np.sqrt(4 * A / np.pi)
         if xa < 60 or xa > 2.2 * TARGET[s]: continue
         yy, xx = np.nonzero(m); cov = np.cov(np.vstack([xx, yy])); ev = np.sort(np.linalg.eigvalsh(cov))
         asp = float(np.sqrt(ev[1] / max(ev[0], 1e-9)))
         solid = m.sum() / max(1, (ndi.binary_fill_holes(m)).sum())
         cands.append((xa, asp, m, (fi, i), p))
    picks = []
    def take(fn):
        rest = [c for c in cands if c[3] not in [q[3] for q in picks]]
        if rest: picks.append(min(rest, key=fn))
    take(lambda c: abs(np.log(c[0] / TARGET[s])) + (0 if c[1] < 1.35 else 5))          # compact, typical size
    take(lambda c: abs(np.log(c[0] / TARGET[s])) + (0 if c[1] > 1.9 else 5))           # elongated
    take(lambda c: abs(np.log(c[0] / (0.6 * TARGET[s]))) + (0 if 1.3 < c[1] < 1.9 else 5))  # smaller, irregular
    lst = []
    for xa, asp, m, _, p in picks:
        m = np.pad(m, 4)
        I, pic = pattern(m.astype(np.float32), p)
        xld = fitx(I, xa)
        sil = Image.fromarray(np.where(m, 40, 255).astype(np.uint8))
        lst.append({'I': [float(f'{v:.4g}') for v in I], 'xA': round(float(xa), 1), 'xLD': round(xld, 1), 'umpx': p, 'asp': round(asp, 2),
                    'sil': b64(sil.convert('L')), 'sw': int(m.shape[1]), 'sh': int(m.shape[0]), 'pat': b64(pic)})
        print(s, 'xA', round(xa, 1), 'xLD', round(xld, 1), 'aspect', round(asp, 2))
    out[s] = {'list': lst}
js = '/* Generated by ld/build.py: Fraunhofer diffraction of real particle silhouettes from the light-microscope images in Zenodo 10.5281/zenodo.16732963 (CC BY 4.0). Do not edit. */\nApp.LDPAT = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open('v2/parts/ldpat.js', 'w').write(js); print(len(js))
