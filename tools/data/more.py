"""Extra real particles from the CT scans (smaller and larger than the main one), mesh + sieve diameter only.
Writes v2/parts/ctmore.js as App.CTMORE[jar] = [..]."""
import glob, json, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.optimize import minimize
from scipy.spatial.transform import Rotation as Rot
from skimage import measure
import trimesh, fast_simplification

VOX = 6.33
MAIN = {'MCC': 193, 'DCPD': 197, 'PGS': 176}
FACT = [0.72, 1.3]
out = {}

def sq_width(P, R):
    Q = P @ R.T; w = Q[:, :2].max(0) - Q[:, :2].min(0); return max(w[0], w[1])

for s in ['MCC', 'DCPD', 'PGS']:
    fs = sorted(glob.glob(f'ct/{s}_[0-9]*.tif'))
    raw = np.stack([np.array(Image.open(f)).astype(np.float32) for f in fs])
    V = ndi.gaussian_filter(raw, 1.0)
    bg = np.median(V); hi = np.percentile(V, 99.5); thr = bg + 0.45 * (hi - bg)
    B = ndi.binary_fill_holes(ndi.binary_opening(V > thr, iterations=1))
    L, n = ndi.label(B)
    cands = []
    for i, sl in enumerate(ndi.find_objects(L)):
        if sl is None: continue
        if any(d.start <= 1 or d.stop >= L.shape[k] - 1 for k, d in enumerate(sl)): continue
        nv = int((L[sl] == i + 1).sum())
        if nv < 1500: continue
        xv = (6 * nv / np.pi) ** (1 / 3) * VOX
        ext = np.array([d.stop - d.start for d in sl]) * VOX
        if ext.max() > 1.9 * xv: continue
        cands.append((xv, i + 1, nv, sl))
    res = []
    for f in FACT:
        tgt = MAIN[s] * f
        xv, lab, nv, sl = min(cands, key=lambda c: abs(np.log(c[0] / tgt)))
        cands = [c for c in cands if c[1] != lab]
        sl = tuple(slice(max(0, d.start - 2), min(L.shape[k], d.stop + 2)) for k, d in enumerate(sl))
        M = (L[sl] == lab)
        sub = ndi.gaussian_filter(np.pad(M, 2).astype(np.float32), 0.8)
        v, fc, _, _ = measure.marching_cubes(sub, 0.5)
        v = v[:, ::-1] * VOX; fc = fc[:, ::-1]
        vv, ff = fast_simplification.simplify(v.astype(np.float32), fc.astype(np.int32), target_reduction=max(0, 1 - 700 / len(fc)))
        m = trimesh.Trimesh(vv, ff, process=True); m.fix_normals()
        P = m.vertices - m.center_mass
        Rs = Rot.random(3000, random_state=2).as_matrix()
        w = np.array([sq_width(P, R) for R in Rs]); bestd, bestR = 1e9, None
        for k in np.argsort(w)[:10]:
            r = minimize(lambda q: sq_width(P, Rot.from_rotvec(q).as_matrix()), Rot.from_matrix(Rs[k]).as_rotvec(), method='Nelder-Mead', options={'xatol': 1e-4, 'fatol': 1e-3, 'maxiter': 600})
            if r.fun < bestd: bestd, bestR = r.fun, Rot.from_rotvec(r.x).as_matrix()
        res.append({'v': np.round(P, 1).ravel().tolist(), 'f': m.faces.ravel().tolist(), 'xV': round(float(xv), 1), 'nvox': nv, 'vox': VOX,
                    'sieve': {'d': round(float(bestd), 1), 'R': np.round(bestR, 5).ravel().tolist()}})
        print(s, 'xV', round(xv), 'sieve', round(bestd, 1))
    out[s] = res
js = '/* Generated by ct/more.py from the X-ray CT scans in Zenodo 10.5281/zenodo.16732963 (CC BY 4.0). Do not edit. */\nApp.CTMORE = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open('v2/parts/ctmore.js', 'w').write(js); print(len(js))
