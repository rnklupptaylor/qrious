# Build parts/jardata.js from the jar_*.json data sheets (rounded fit coefficients as printed).
import json, math, sys, os
J=sys.argv[1] if len(sys.argv)>1 else os.path.join(os.path.dirname(__file__),'../../jars')
OUT=os.path.join(os.path.dirname(__file__),'../parts/jardata.js')
def r6(v): return float('%.6g'%v)
out={}
for jid in ['MCC','DCPD','PGS','NM-200','NM-203','GB-B','CEM']:
    d=json.load(open(os.path.join(J,'jar_%s.json'%jid))); ms=[]
    for m in d['methods']:
        unit=m.get('unit','µm')
        if 'points' in m:   # cement: shares per instrument class; limits halfway (geometric) between the published sizes
            x=m['points']['x_um']; v=m['points']['q3_per_um']
            e=[x[0]**1.5/x[1]**0.5]+[math.sqrt(a*b) for a,b in zip(x[:-1],x[1:])]+[x[-1]**1.5/x[-2]**0.5]
            amt=v
            # drop empty classes at both ends
            i0=next(i for i,a in enumerate(amt) if a>0); i1=len(amt)-next(i for i,a in enumerate(reversed(amt)) if a>0)
            e=e[i0:i1+1]; amt=amt[i0:i1]; lab='%'
        else:
            e=m.get('edges_um') or m.get('edges'); amt=m.get('amount') or m.get('percent'); lab=m.get('amount_label') or '%'
            if lab=='volume %': lab='%'
        f=m.get('fit'); fit=None
        why=None
        if f and f.get('maxdQ',0)>0.1: why='shape'; f=None   # a few quadratic pieces cannot follow it: keep discrete
        elif not f and 'points' not in m: why='narrow'
        if f: fit={'k':[r6(k) for k in (f.get('knots_um') or f.get('knots'))],'c':[[c for c in row] for row in f['coef']],'gap':round(f.get('maxdQ',0),4)}
        ms.append({'key':m['key'],'r':m['r'],'unit':unit,'e':[r6(v) for v in e],'m':[r6(v) for v in amt],'ml':lab,'fit':fit,'why':why})
    out[jid]=ms
js='/* Generated by tools/jardata.py from the jar data sheets. Do not edit by hand. */\nApp.JARDATA = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n'
open(OUT,'w').write(js); print(len(js))
